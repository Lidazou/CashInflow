/**
 * The preload bridge — the ONLY surface the renderer can reach.
 *
 * SECURITY (spec §5, §39)
 * ----------------------
 * - `contextIsolation: true` and `nodeIntegration: false` mean renderer code
 *   cannot `require('fs')`, `require('child_process')` or reach the database.
 * - This file never exposes `ipcRenderer` itself. Exposing the raw object would
 *   let any renderer script invoke arbitrary channels, which would defeat the
 *   whole allow-list. Instead every method below names one channel explicitly.
 * - Arguments are structured-cloned across the boundary, so functions, class
 *   instances and prototypes cannot cross. That is a feature: it guarantees the
 *   main process receives plain, inspectable data.
 * - Results arrive as an `IpcResult` envelope. Failures are re-thrown here as a
 *   real `Error` with the original `code` and `fields` attached, so callers can
 *   `try/catch` naturally while the UI can still branch on the error code and
 *   highlight specific form fields.
 */

/** An error reconstructed on the renderer side from a main-process failure. */
export interface BridgeError extends Error {
  code: string
  fields?: Record<string, string>
}

function makeError(error: { code: string; message: string; fields?: Record<string, string> }): BridgeError {
  const constructed = new Error(error.message) as BridgeError
  constructed.code = error.code
  if (error.fields) constructed.fields = error.fields
  return constructed
}

/**
 * Invoke a channel and unwrap the envelope.
 *
 * The `IpcResult` is resolved by main, never rejected, so this is the single
 * place that decides how a failure surfaces in the renderer.
 */
async function invoke<T>(channel: string, ...args: unknown[]): Promise<T> {
  const result = (await ipcRenderer.invoke(channel, ...args)) as IpcResult<T> | undefined

  // A missing envelope means the handler was never registered —a wiring bug
  // rather than a data problem, so say that rather than returning undefined and
  // letting the UI render a blank field.
  if (!result || typeof result !== 'object' || !('ok' in result)) {
    throw makeError({
      code: 'INTERNAL',
      message: `No response from the application for "${channel}". This is a bug; please report it.`
    })
  }

  if (result.ok) return result.data
  throw makeError(result.error)
}

