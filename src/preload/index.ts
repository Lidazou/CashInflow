  /**
   * Subscribe to data-change notifications.
   *
   * The listener is wrapped so the renderer's callback never receives the raw
   * Electron event object, which carries a `sender` capable of reaching back
   * into the IPC layer.
   *
   * Returns an unsubscribe function; React effects must call it on cleanup or
   * listeners accumulate on every mount.
   */
  onDataChanged: (callback: (payload: { reason: string }) => void): (() => void) => {
    const listener = (_event: unknown, payload: { reason: string }): void => {
      callback({ reason: payload?.reason ?? 'unknown' })
    }
    ipcRenderer.on(IPC_CHANNELS.eventDataChanged, listener)
    return () => {
      ipcRenderer.removeListener(IPC_CHANNELS.eventDataChanged, listener)
    }
  }
